    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        String name = vetName.getText().trim();
        String phone = phonetxt.getText().trim();
        String specialization = specialcmb.getSelectedItem().toString();

    if (name.isEmpty() || phone.isEmpty() || specialization.isEmpty()) {
             JOptionPane.showMessageDialog(this,
            "Please fill in all fields.");
                return;
    }

    try {
        Veterinarian vet = new Veterinarian();

        vet.setName(name);
        vet.setPhone(phone);
        vet.setSpecialization(specialization);

         boolean added = vetDAO.addVeterinarian(vet);

        if (added) {
            JOptionPane.showMessageDialog(this,
                "Veterinarian added successfully!");

            loadVeterinarians();

            vetName.setText("");
            phonetxt.setText("");
            specialcmb.setSelectedIndex(0);
        }
} 
    catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error adding veterinarian: " + e.getMessage());
    }//GEN-LAST:event_btnAddActionPerformed
}
    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
       int selectedRow = vettbl.getSelectedRow();

    if (selectedRow == -1) {
        
    JOptionPane.showMessageDialog(this,
            "Please select a veterinarian from the table.");
    return;
}

    String name = vetName.getText().trim();
    String phone = phonetxt.getText().trim();
    String specialization = specialcmb.getSelectedItem().toString();

    if (name.isEmpty() || phone.isEmpty() || specialization.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please fill in all fields.");
    return;
    }

    try {
        
    Veterinarian vet = new Veterinarian();

    vet.setVetId(Integer.parseInt(VetIdtxt.getText()));
    vet.setName(name);
    vet.setPhone(phone);
    vet.setSpecialization(specialization);

    boolean updated = vetDAO.updateVeterinarian(vet);

    if (updated) {
        JOptionPane.showMessageDialog(this,
                "Veterinarian updated successfully!");

        loadVeterinarians();

        vetName.setText("");
        phonetxt.setText("");
        specialcmb.setSelectedIndex(0);
        VetIdtxt.setText("");
    } else {
        JOptionPane.showMessageDialog(this,
                "Veterinarian was not found.");
    }

} 
    catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error updating veterinarian: " + e.getMessage());
    } 
    catch (NumberFormatException e) {
         JOptionPane.showMessageDialog(this,
            "Please select a valid veterinarian.");
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

