    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        
        String keyword = searchvettxt.getText().trim();

    if (keyword.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Please enter a name, phone number, ID, or specialization.");
        return;
    }

    try {
        
    DefaultTableModel model = (DefaultTableModel) vettbl.getModel();
    model.setRowCount(0);

    for (Veterinarian vet : vetDAO.searchVeterinarians(keyword)) {
        model.addRow(new Object[]{
            vet.getVetId(),
            vet.getName(),
            vet.getPhone(),
            vet.getSpecialization()
        });
    }

    if (model.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this,
                "No veterinarian found.");
    }

}
    catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error searching veterinarians: " + e.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

