    private void loadVeterinarians() {
    try {
        DefaultTableModel model = (DefaultTableModel) vettbl.getModel();
        model.setRowCount(0);

        for (Veterinarian vet : vetDAO.getAllVeterinarians()) {
            model.addRow(new Object[]{
                vet.getVetId(),
                vet.getName(),
                vet.getPhone(),
                vet.getSpecialization()
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading veterinarians: " + e.getMessage());
    }
}
    
