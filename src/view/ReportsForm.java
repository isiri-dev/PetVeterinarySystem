    private void showJasperReport(String fileName) {
        try (Connection con = DBConnection.getConnection()) {
            JasperPrint print = JasperFillManager.fillReport(
                    "reports/" + fileName + ".jasper", new HashMap<>(), con);
            JasperViewer.viewReport(print, false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Report error: " + e.getMessage());
        }
    }

    private void loadReportData() {

    String reportType = cmbReportType.getSelectedItem().toString();

    String sql ;

    switch (reportType) {
        case "Customers" -> sql = "SELECT * FROM customers";
        case "Pets" -> sql = "SELECT * FROM pets";
        case "Veterinarians" -> sql = "SELECT * FROM veterinarians";
        case "Appointments" -> sql = "SELECT * FROM appointments";
        case "Payments" -> sql = "SELECT * FROM payments";

        case "Select Report Type" -> {
            JOptionPane.showMessageDialog(
                    this,
                    "Please select a report type first!"
            );
            return;
        }

        default -> {
            JOptionPane.showMessageDialog(
                    this,
                    "Invalid report type!"
            );
            return;
        }
    }

    try (Connection con = DBConnection.getConnection();
     PreparedStatement pst = con.prepareStatement(sql);
     ResultSet rs = pst.executeQuery()) {

    DefaultTableModel model =
            (DefaultTableModel) tblReports.getModel();

    model.setRowCount(0);
    model.setColumnCount(0);

    java.sql.ResultSetMetaData metaData = rs.getMetaData();
    int columnCount = metaData.getColumnCount();

    for (int i = 1; i <= columnCount; i++) {
        model.addColumn(metaData.getColumnName(i));
    }

    while (rs.next()) {
        Object[] row = new Object[columnCount];

        for (int i = 1; i <= columnCount; i++) {
            row[i - 1] = rs.getObject(i);
        }

        model.addRow(row);
    }

} catch (SQLException e) {
    JOptionPane.showMessageDialog(
            this,
            "Error loading report: " + e.getMessage()
    );
}
   
}
   

